#!/usr/bin/env node
/**
 * build-questions.js
 * ------------------------------------------------------------
 * Regenerates js/questionData.js from data/questions.json.
 *
 * Run this any time you edit data/questions.json (add, remove,
 * or fix questions) so the changes take effect in the app:
 *
 *     node build-questions.js
 *
 * The app itself only reads js/questionData.js (loading raw
 * JSON via fetch() would fail when the site is opened directly
 * from disk as a file:// URL, so the data is embedded as a
 * plain JS file instead).
 * ------------------------------------------------------------
 */

const fs = require('fs');
const path = require('path');

const dataPath = path.join(__dirname, 'data', 'questions.json');
const outPath = path.join(__dirname, 'js', 'questionData.js');

let raw = fs.readFileSync(dataPath, 'utf8');
if (raw.charCodeAt(0) === 0xFEFF) raw = raw.slice(1); // strip UTF-8 BOM, if present
const data = JSON.parse(raw); // throws with a useful message if the JSON is invalid

const banner = `// ============================================================
// QUESTION BANK DATA
// ============================================================
// Auto-generated from data/questions.json by build-questions.js.
// Do NOT edit this file by hand -- edit data/questions.json and
// re-run "node build-questions.js" instead.
//
// Each section is a plain array of question objects:
//   { id, question, options: [{key, text}, ...], answer }
// "answer" is the option key ("A"|"B"|"C"|"D") that is correct.
// ============================================================

window.QUESTION_BANK = `;

fs.writeFileSync(outPath, banner + JSON.stringify(data, null, 2) + ';\n', 'utf8');

const counts = Object.fromEntries(Object.entries(data).map(([k, v]) => [k, v.length]));
console.log('Regenerated js/questionData.js');
console.log('Question counts:', counts);
